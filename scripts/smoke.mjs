import assert from 'node:assert/strict';
const frontend=process.env.PREVIEW_URL||'http://127.0.0.1:5173';
const backend=process.env.API_URL||'http://127.0.0.1:3001';
const page=await fetch(frontend);
assert.equal(page.status,200);
assert.match(await page.text(),/Sukanya Bhattacharyya/);
const production=await fetch(backend);
assert.equal(production.status,200);
const html=await production.text();
const asset=html.match(/src="([^"]+\.js)"/);
assert.ok(asset,'Production JavaScript asset exists');
assert.equal((await fetch(backend+asset[1])).status,200);
assert.ok(production.headers.get('content-security-policy'));
const contact=await fetch(backend+'/contact');
assert.equal(contact.status,200);
const contactHtml=await contact.text();
assert.match(contactHtml,/<title>Contact \| Sukanya Bhattacharyya<\/title>/);
assert.match(contactHtml,/Connect with Sukanya/);
assert.equal((await fetch(frontend+'/contact')).status,200);
assert.equal((await fetch(backend+'/not-a-page')).status,404);
const invalid=await fetch(frontend+'/api/contact',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'Invalid visitor'})});
assert.equal(invalid.status,400);
assert.match((await invalid.json()).error,/email/);
const trap=await fetch(frontend+'/api/contact',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({website:'bot'})});
assert.equal(trap.status,202);
assert.equal((await trap.json()).accepted,false);
console.log('HTTP smoke checks passed: homepage and /contact, production metadata and asset, CSP, 404, proxied API validation, honeypot. No live email sent.');
